# ---------- строительные блоки ----------
def p(text, style="body"):
    if style == "body" and text.rstrip().endswith(":"):
        style = "lead"  # вводная «…:» не отрывается от следующего блока
    return Paragraph(text, S[style])


def c(text):
    return f'<font name="Mono" size="8.8" color="#0b3d7a">{escape(text)}</font>'


def bullets(items):
    return [Paragraph(t, S["bullet"], bulletText="•") for t in items]


def code(text):
    t = Table([[Preformatted(text.strip("\n"), S["code"])]], colWidths=[W])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), CODE_BG), ("BOX", (0, 0), (-1, -1), 0.5, RULE),
        ("LEFTPADDING", (0, 0), (-1, -1), 8), ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    return KeepTogether([t, Spacer(1, 6)])


def note(text, info=False):
    bg, border = (INFO_BG, INFO_BORDER) if info else (WARN_BG, WARN_BORDER)
    t = Table([[Paragraph(text, S["note"])]], colWidths=[W])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), bg), ("LINEBEFORE", (0, 0), (0, -1), 3, border),
        ("LEFTPADDING", (0, 0), (-1, -1), 9), ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    return KeepTogether([t, Spacer(1, 7)])


def table(header, rows, widths):
    data = [[Paragraph(h, S["cellh"]) for h in header]] + [[Paragraph(x, S["cell"]) for x in r] for r in rows]
    t = Table(data, colWidths=[W * w for w in widths], repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), CODE_BG), ("LINEBELOW", (0, 0), (-1, 0), 0.8, MUTED),
        ("LINEBELOW", (0, 1), (-1, -1), 0.4, RULE), ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 5), ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    if t.wrap(W, A4[1])[1] > 70 * mm:  # длинная таблица делится между страницами
        return [t, Spacer(1, 8)]
    return KeepTogether([t, Spacer(1, 8)])


class Doc:
    def __init__(self):
        self.story = []
        self.n = 0

    def add(self, x):
        story = self.story
        if isinstance(x, list):
            story.extend(x)
            return
        if isinstance(x, Paragraph) and x.style.name in ("h1", "h2"):
            story.append(CondPageBreak(60 * mm if x.style.name == "h1" else 45 * mm))
        story.append(x)

    def h1(self, text):
        self.n += 1
        self.add(p(f"{self.n}. {text}", "h1"))

    def h2(self, text):
        self.add(p(text, "h2"))

    def __call__(self, *xs):
        for x in xs:
            self.add(x)


