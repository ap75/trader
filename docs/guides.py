def footer_for(role):
    names = {"admin": T("администратор", "адміністратор"), "trader": T("трейдер", "трейдер"),
             "viewer": T("зритель", "глядач")}
    label = T("Бот опционов Bybit — инструкция: ", "Бот опціонів Bybit — інструкція: ") + names[role]
    page = T("стр.", "стор.")

    def on_page(canvas, doc):
        canvas.saveState()
        canvas.setFont("Sans", 7.8)
        canvas.setFillColor(MUTED)
        canvas.drawString(18 * mm, 11 * mm, label)
        canvas.drawRightString(A4[0] - 18 * mm, 11 * mm, f"{page} {doc.page}")
        canvas.setStrokeColor(RULE)
        canvas.setLineWidth(0.5)
        canvas.line(18 * mm, 14 * mm, A4[0] - 18 * mm, 14 * mm)
        canvas.restoreState()
    return on_page, label


def build(role: str, lang: str, out_dir: str) -> str:
    global LANG
    LANG = lang
    d = Doc()
    title(d, role)
    if role == "admin":
        d(p(T("Эта инструкция — для владельца счёта и бота: доступ, настройки, запуск, развёртывание на VPS и "
              "переход на mainnet. Работа с командами описана в инструкции для трейдера.",
              "Ця інструкція — для власника рахунку та бота: доступ, налаштування, запуск, розгортання на VPS і "
              "перехід на mainnet. Роботу з командами описано в інструкції для трейдера.")))
        admin_access(d)
        admin_settings(d)
        admin_run(d)
        admin_data(d)
        admin_vps(d)
        admin_mainnet(d)
        admin_cli(d)
        admin_logs(d)
        sec_where(d, role)
        sec_trading(d)
        sec_confirm(d)
    else:
        sec_quick_start(d, role)
        sec_where(d, role)
        sec_view(d)
        sec_signals(d, role)
        sec_account(d, role)
        if role == "trader":
            sec_trading(d)
            sec_confirm(d)
        sec_notifications(d, role)
        trouble(d, role)
    on_page, label = footer_for(role)
    path = os.path.join(out_dir, f"guide-{role}-{lang}.pdf")
    SimpleDocTemplate(path, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm,
                      bottomMargin=20 * mm, title=label, author="optbot").build(
        d.story, onFirstPage=on_page, onLaterPages=on_page)
    return path


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "docs"
    for role in ("admin", "trader", "viewer"):
        for lang in ("ru", "uk"):
            print("ok", build(role, lang, out))
